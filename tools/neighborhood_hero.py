    body = list(_HEAD_BODY)
    if phase == 0:
        body[22:26] = (".3223222222323..", ".3113333333323..",
                       ".3113321133313..", "..33.333333.13..")
    elif phase == 1:
        body[22:26] = (".3223222222323..", ".3113333333313..",
                       ".3113321133313..", "..33.333333.33..")
    elif phase == 2:
        body[22:26] = (".3223222222323..", ".3223333333313..",
                       ".3113321133313..", ".31..333333.33..")
    else:
        body[22:26] = (".3223222222323..", ".3113333333313..",
                       ".3113321133313..", "..33.333333.33..")
    return tuple(body) + _WALK_LEGS[phase]


