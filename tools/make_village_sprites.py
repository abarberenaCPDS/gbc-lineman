    grids = [(f"player:{name}", grid) for name, grid in _PLAYER_GRIDS.items()]
    grids += [(f"folk:{name}", data[0]) for name, data in folk_meta.items()]
    grids += [(f"props:{name}", data[0]) for name, data in props_meta.items()]
    for name, grid in grids:
        validate_grid(grid, name)

    player_states = [{
        "name": "",
        "animationType": "multi_movement",
        "flipLeft": False,
        "animations": player_meta["animations"],
    }]
    folk_states = [
        {
            "name": name,
            "animationType": "fixed",
            "flipLeft": False,
            "animations": [[i]] + [[None] for _ in range(7)],
        }
        for i, name in enumerate(folk_meta)
    ]
    prop_states = [
        {
            "name": name,
            "animationType": "fixed",
            "flipLeft": False,
            "animations": [[i]] + [[None] for _ in range(7)],
        }
        for i, name in enumerate(props_meta)
    ]
    player_tiles, player_oam = write_asset(
        "village_player", player_sheet, player_states, ["hero"]
    )
    folk_tiles, folk_oam = write_asset(
        "village_folk", folk_sheet, folk_states,
        [folk_meta[name][1] for name in folk_meta],
    )
    prop_tiles, prop_oam = write_asset(
        "village_props", props_sheet, prop_states, ["glow"] * len(props_meta)
    )
    total = player_tiles + folk_tiles + prop_tiles
    assert total <= 192, f"sprite tile budget exceeded: {total}/192"  # L-11
    print(f"sprite budget: {total}/192 unique 8x16 tiles across all three sheets")
    max_oam = max(player_oam, folk_oam, prop_oam)
    assert max_oam <= 2, f"authored OBJ pieces per frame exceed the 2-object limit: {max_oam}/2"
    print(f"authored OBJ pieces per frame: max {max_oam}/2 (8x16 objects)")

    preview_sheet(
        [(f"{name} {i}", _PLAYER_GRIDS[name], "hero")
         for i, name in enumerate(_PLAYER_SHEET_ORDER)],
        "village_player_frames_4x.png",
    )
    preview_sheet(
        [(name, folk_meta[name][0], folk_meta[name][1]) for name in folk_meta],
        "village_folk_frames_4x.png",
    )
    preview_sheet(
        [(name, props_meta[name][0], props_meta[name][1]) for name in props_meta],
        "village_props_frames_4x.png",
    )


