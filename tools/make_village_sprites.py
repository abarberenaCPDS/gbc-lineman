def make_player() -> tuple[Image.Image, dict]:
    idx = {name: i for i, name in enumerate(_PLAYER_SHEET_ORDER)}
    # Stored slot order: 0 idle right, 1 idle left, 2 idle up, 3 idle down,
    # 4 moving right, 5 moving left, 6 moving up, 7 moving down.
    animations = [
        [idx["right_idle"]],
        [idx["left_idle"]],
        [idx["up_idle"]],
        [idx["down_idle"]],
        [idx["right_a"], idx["right_b"], idx["right_idle"]],
        [idx["left_a"], idx["left_b"], idx["left_idle"]],
        [idx["up_a"], idx["up_b"], idx["up_idle"]],
        [idx["down_a"], idx["down_b"], idx["down_idle"]],
    ]
    frames = [grid_frame(_PLAYER_GRIDS[name]) for name in _PLAYER_SHEET_ORDER]
    sheet = Image.new("RGBA", (FRAME_W * len(frames), FRAME_H), TRANSPARENT)
    for i, frame in enumerate(frames):
        sheet.paste(frame, (i * FRAME_W, 0))
    return sheet, {"palette": "hero", "animations": animations}


