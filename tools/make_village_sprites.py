"""Generate the village character and prop sprites for "Mister CFE: After the Storm".

Run with the project's managed Python (which provides Pillow):

    python tools/make_village_sprites.py

Art is authored here as explicit 16x16 pixel grids, one string per row:

    '.' transparent, '1' dark, '2' mid, '3' light

Every digit is painted into the PNG with a bucket-proxy color so that GB
Studio's luminance-based sprite conversion (``spriteDataIndexFn``: alpha<200
-> transparent, g >= 205 -> hw value 1, 130 <= g < 205 -> hw value 2,
g < 130 -> hw value 3) puts the pixel in the intended hardware slot.  The
compiler loads each sprite palette as ``[c0, c0, c1, c3]``, so inside the ROM
the digits render as the ``village.py`` ramp entries:

    '1' -> colors[0] (near-black outline)
    '2' -> colors[1] (body shade)
    '3' -> colors[3] (light shade)

Preview sheets are rendered through exactly that pipeline (proxy -> bucket ->
hardware value -> ramp color), so what you see is what the ROM draws.
``tools/village.py`` is the palette and design source of truth; palette slots
follow ``SPRITE_PALETTES`` order: hero 0, folk_a 1, folk_b 2, folk_c 3,
prop 4, glow 5.  All resource IDs are deterministic uuid5 values.
"""

