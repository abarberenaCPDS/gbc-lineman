# Bucket-proxy colors; the green channel picks the hardware slot.
PROXY = {
    1: (236, 240, 244, 255),  # g=240 -> hw 1 (outline shade)
    2: (96, 176, 208, 255),   # g=176 -> hw 2 (body shade)
    3: (120, 88, 24, 255),    # g=88  -> hw 3 (light shade)
}


def stable_id(key: str) -> str:
    return str(uuid.uuid5(NAMESPACE, f"modretro-chromatic:mr-cfe:{key}"))


# ---------------------------------------------------------------------------
# Grid plumbing
# ---------------------------------------------------------------------------

def validate_grid(grid: list[str], name: str) -> None:
    assert len(grid) == FRAME_H, f"{name}: needs {FRAME_H} rows, got {len(grid)}"
    for y, row in enumerate(grid):
        assert len(row) == FRAME_W, f"{name}: row {y} is {len(row)} chars"
        assert all(ch in "0123." for ch in row), f"{name}: bad char in row {y}"

    def is_open(x: int, y: int) -> bool:
        return 0 <= x < FRAME_W and 0 <= y < FRAME_H and grid[y][x] == "."

    for y, row in enumerate(grid):
        for x, ch in enumerate(row):
            if ch in ".1":
                continue
            if (
                is_open(x - 1, y)
                or is_open(x + 1, y)
                or is_open(x, y - 1)
                or is_open(x, y + 1)
            ):
                raise ValueError(
                    f"{name}: pixel {ch!r} at {x},{y} touches transparency without a '1' outline"
                )


def grid_frame(grid: list[str]) -> Image.Image:
    image = Image.new("RGBA", (FRAME_W, FRAME_H), TRANSPARENT)
    for y, row in enumerate(grid):
        for x, ch in enumerate(row):
            if ch != ".":
                image.putpixel((x, y), PROXY[int(ch)])
    return image



