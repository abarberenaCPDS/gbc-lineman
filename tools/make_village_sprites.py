# Sidecar construction
# ---------------------------------------------------------------------------

def tile_pixels(sheet: Image.Image, x: int) -> tuple[int, ...]:
    """Return an 8x16 row-major signature in GB Studio hardware shade indices."""
    values = []
    for y in range(FRAME_H):
        for px in range(x, x + TILE):
            r, g, b, a = sheet.getpixel((px, y))
            if a < 200 or (g > 249 and r < 180 and b < 20) or (b >= 200 and g < 20):
                values.append(0)
            elif g >= 205:
                values.append(1)
            elif g >= 130:
                values.append(2)
            else:
                values.append(3)
    return tuple(values)


def make_metasprite(asset_name: str, frame_index: int, sheet: Image.Image,
                    palette_slot: int, state_index: int) -> dict:
    tiles = []
    for col, x in enumerate((0, 8)):
        signature = tile_pixels(sheet, frame_index * FRAME_W + x)
        if all(value == 0 for value in signature):
            continue
        tiles.append({
            "id": stable_id(f"{asset_name}:tile:{state_index}:{frame_index}:{col}"),
            "x": x, "y": 0,
            "sliceX": frame_index * FRAME_W + x, "sliceY": 0,
            "flipX": False, "flipY": False,
            "palette": 0, "paletteIndex": palette_slot,
            "objPalette": "OBP0", "priority": False,
        })
    return {"id": stable_id(f"{asset_name}:frame:{state_index}:{frame_index}"), "tiles": tiles}


def build_sidecar(asset_name: str, sheet: Image.Image, states: list[dict],
                  state_palettes: list[str]) -> tuple[dict, int, int]:
    state_resources = []
    unique_tiles: set[tuple[int, ...]] = set()
    frame_count = sheet.width // FRAME_W
    for state_index, state in enumerate(states):
        animations = []
        palette_slot = PALETTE_SLOTS[state_palettes[state_index]]
        for anim_index, source_frames in enumerate(state["animations"]):
            metasprite_frames = []
            for source_frame in source_frames:
                if source_frame is None:
                    metasprite = {
                        "id": stable_id(
                            f"{asset_name}:state:{state_index}:empty-frame:{anim_index}"
                        ),
                        "tiles": [],
                    }
                else:
                    if not 0 <= source_frame < frame_count:
                        raise ValueError(f"{asset_name}: bad source frame {source_frame}")
                    metasprite = make_metasprite(
                        asset_name, source_frame, sheet, palette_slot, state_index
                    )
                metasprite_frames.append(metasprite)
                for tile in metasprite["tiles"]:
                    unique_tiles.add(tile_pixels(sheet, tile["sliceX"]))
            animations.append({
                "id": stable_id(f"{asset_name}:state:{state_index}:animation:{anim_index}"),
                "frames": metasprite_frames,
            })
        state_resources.append({
            "id": stable_id(f"{asset_name}:state:{state_index}"),
            "name": state["name"],
            "animationType": state["animationType"],
            "flipLeft": state["flipLeft"],
            "animations": animations,
        })
    sidecar = {
        "_resourceType": "sprite",
        "id": stable_id(f"resource:{asset_name}"),
        "name": asset_name,
        "symbol": f"sprite_{asset_name}",
        "states": state_resources,
        "numTiles": len(unique_tiles),
        "canvasOriginX": 0,
        "canvasOriginY": 0,
        "canvasWidth": FRAME_W,
        "canvasHeight": FRAME_H,
        "boundsX": 0,
        "boundsY": -8 if asset_name == "village_player" else 0,
        "boundsWidth": FRAME_W,
        "boundsHeight": FRAME_H if asset_name == "village_player" else 8,
        "animSpeed": 15,
        "filename": f"{asset_name}.png",
        "width": sheet.width,
        "height": sheet.height,
        "spriteMode": "8x16",
        "checksum": "",
    }
    max_frame_objects = max(
        (
            len(frame["tiles"])
            for state in state_resources
            for animation in state["animations"]
            for frame in animation["frames"]
        ),
        default=0,
    )
    if max_frame_objects > 2:
        raise ValueError(
            f"{asset_name}: authored frame uses {max_frame_objects} OBJ pieces; limit is 2"
        )
    return sidecar, len(unique_tiles), max_frame_objects


def output_belongs_to_generator(asset_name: str, png_path: Path, sidecar_path: Path) -> None:
    if not png_path.exists() and not sidecar_path.exists():
        return
    if not (png_path.exists() and sidecar_path.exists()):
        raise FileExistsError(f"Refusing to replace unpaired generated output: {png_path}")
    existing = json.loads(sidecar_path.read_text(encoding="utf-8"))
    expected_id = stable_id(f"resource:{asset_name}")
    if existing.get("id") != expected_id:
        raise FileExistsError(f"Refusing to replace unowned sprite: {sidecar_path}")


def write_asset(asset_name: str, sheet: Image.Image, states: list[dict],
                palettes: list[str]) -> tuple[int, int]:
    png_path = OUT_DIR / f"{asset_name}.png"
    sidecar_path = Path(f"{png_path}.gbsres")
    output_belongs_to_generator(asset_name, png_path, sidecar_path)
    if sheet.height != FRAME_H or sheet.width % FRAME_W:
        raise ValueError(f"{asset_name}: non-16x16-aligned sheet {sheet.size}")
    # Every pixel is transparent or one of the three intended indexed shades;
    # every 8x8 hardware tile therefore has at most four colors.
    allowed = {TRANSPARENT, *PROXY.values()}
    if not set(sheet.get_flattened_data()) <= allowed:
        raise ValueError(f"{asset_name}: pixel outside the authored sprite palette")
    for y in range(0, sheet.height, 8):
        for x in range(0, sheet.width, 8):
            if len(set(sheet.crop((x, y, x + 8, y + 8)).get_flattened_data())) > 4:
                raise ValueError(f"{asset_name}: >4 colors in 8x8 tile {x},{y}")
    sidecar, unique, max_frame_objects = build_sidecar(asset_name, sheet, states, palettes)
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    sheet.save(png_path, format="PNG", optimize=False)
    sidecar["checksum"] = hashlib.sha1(png_path.read_bytes()).hexdigest()
    sidecar_path.write_text(json.dumps(sidecar, indent=2) + "\n", encoding="utf-8")
    with Image.open(png_path) as written:
        if written.mode != "RGBA" or written.size != (sidecar["width"], sidecar["height"]):
            raise ValueError(f"{asset_name}: persisted PNG metadata mismatch")
    reread = json.loads(sidecar_path.read_text(encoding="utf-8"))
    if reread != sidecar or reread["checksum"] != hashlib.sha1(png_path.read_bytes()).hexdigest():
        raise ValueError(f"{asset_name}: sidecar round-trip/checksum mismatch")
    print(f"assets/sprites/{asset_name}.png + sidecar: {sheet.width}x{sheet.height}, {unique} unique 8x16 tiles")
    print(f"  resource ID: {sidecar['id']}")
    return unique, max_frame_objects


# ---------------------------------------------------------------------------
# Hardware-true 4x nearest-neighbour contact sheets
# ---------------------------------------------------------------------------

def hardware_render(grid: list[str], palette: str) -> Image.Image:
    colors = HW_RAMP_COLORS[palette]
    result = Image.new("RGBA", (FRAME_W, FRAME_H), TRANSPARENT)
    for y, row in enumerate(grid):
        for x, ch in enumerate(row):
            if ch != ".":
                result.putpixel((x, y), colors[int(ch)])
    return result


def preview_sheet(entries: list[tuple[str, list[str], str]], filename: str) -> Path:
    scale, padding, label_height = 4, 4, 12
    cell = FRAME_W * scale
    width = padding + len(entries) * (cell + padding)
    height = padding + cell + label_height + padding
    image = Image.new("RGBA", (width, height), (32, 36, 48, 255))
    draw = ImageDraw.Draw(image)
    for i, (label, grid, palette) in enumerate(entries):
        x = padding + i * (cell + padding)
        y = padding
        for py in range(0, cell, 8):
            for px in range(0, cell, 8):
                c = (64, 68, 84, 255) if ((px // 8) + (py // 8)) % 2 == 0 else (88, 92, 108, 255)
                draw.rectangle((x + px, y + py, x + px + 7, y + py + 7), fill=c)
        frame = hardware_render(grid, palette).resize((cell, cell), Image.Resampling.NEAREST)
        image.alpha_composite(frame, (x, y))
        draw.text((x, y + cell + 1), label, fill=(235, 236, 240, 255))
    EVIDENCE_DIR.mkdir(parents=True, exist_ok=True)
    path = EVIDENCE_DIR / filename
    image.save(path)
    print(f"preview sheet: {path}")
    return path


